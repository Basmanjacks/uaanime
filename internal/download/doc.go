// Package download зберігає серію на диск користувача за його явною дією:
// розбирає HLS-плейлист, планує варіанти якості, тягне сегменти й склеює їх
// в один файл поруч із бібліотекою.
//
// Форми HLS, на які розрахований розбір, перевірені наживо 2026-09-16 на
// ashdi.vip, tortuga.tw і moonanime.art (лише читання, curl-ом): майстер із
// #EXT-X-STREAM-INF (RESOLUTION+BANDWIDTH, порядок атрибутів у хостів різний),
// медіаплейлисти VOD з #EXT-X-VERSION:3, #EXTINF і #EXT-X-ENDLIST, 160–312
// сегментів; жоден хост не віддавав #EXT-X-KEY, #EXT-X-MAP чи #EXT-X-BYTERANGE.
// URL сегментів бувають абсолютні (ashdi, moon — ще й на іншому піддомені, ніж
// плейлист) і відносні (tortuga: «segment1.ts»). Це не гарантія на майбутнє:
// плейлист — недовірені дані, тож усе, що виходить за перевірені форми, пакет
// відхиляє окремим сентинелом, а не намагається вгадати.
//
// Пакет ніколи не імпортує internal/playback — залежність іде навпаки:
// playback знає про збережені файли, download про відтворення не знає нічого.
